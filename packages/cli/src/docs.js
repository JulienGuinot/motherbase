'use strict';

// Renders the command registry as the Markdown table published in the docs.
//
// `main.js` already builds every help screen from `registry` + `groups`, so the
// terminal could never disagree with the code. The published CLI reference
// could, and did: thirteen whole groups (`orgs`, `branches`, `domains`,
// `vanity-subdomains`, `backups`, `test`, `postgres-config`, `queues`, `vault`,
// `wrappers`, `network-restrictions`, `ssl-enforcement`, `snippets`) existed in
// `motherbase --help` and not in the reference, so the documented CLI was a
// strict subset of the shipped one.
//
// Writing it from the same two objects the help screens use is what stops that
// happening again. `scripts/generate-cli-docs.js` writes the file;
// `test/docs.test.js` fails when the committed copy no longer matches.

const { registry, groups } = require('./commands');

/** Escape the pipe so a usage string containing one cannot break the table. */
const cell = value => String(value ?? '').replace(/\|/g, '\\|');

/** `motherbase db sql -e <sql>` → `` `motherbase db sql` `` plus its arguments. */
function usageCell(usage) {
  return usage ? `\`${cell(usage)}\`` : '—';
}

/**
 * Commands in group order, then whatever the registry holds that no group
 * names. A command with no group still renders: adding one to the registry and
 * forgetting the group list must not make it vanish from the docs.
 */
function sections() {
  const grouped = new Set(groups.flatMap(group => group.names));
  const ungrouped = Object.keys(registry).filter(name => !grouped.has(name));
  const all = groups.map(group => ({ title: group.title, names: group.names }));
  if (ungrouped.length) all.push({ title: 'Ungrouped', names: ungrouped });
  return all;
}

function renderCommandDocs() {
  const lines = [
    '<!-- GENERATED by `npm run docs:cli` from packages/cli/src/commands. Do not edit by hand. -->',
    '',
  ];

  for (const section of sections()) {
    const entries = section.names.map(name => [name, registry[name]]).filter(([, entry]) => entry);
    if (!entries.length) continue;

    lines.push(`### ${section.title}`, '');
    lines.push('| Command | Usage | What it does |');
    lines.push('|---|---|---|');

    for (const [name, entry] of entries) {
      lines.push(`| \`${cell(name)}\` | ${usageCell(entry.usage)} | ${cell(entry.summary)} |`);
      for (const [sub, subEntry] of Object.entries(entry.subcommands ?? {})) {
        lines.push(
          `| \`${cell(name)} ${cell(sub)}\` | ${usageCell(subEntry.usage)} | ${cell(subEntry.summary)} |`,
        );
      }
    }
    lines.push('');
  }

  return lines.join('\n');
}

module.exports = { renderCommandDocs };
