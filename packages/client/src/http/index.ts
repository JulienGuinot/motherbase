import { HTTP_ROUTES } from "@motherbase/contracts";
import { SessionStore } from "../auth/session.js";
import { RequestEvent, RequestObserver, RequestOptions } from "./types.js";
import { isBrowser } from "../utils/runtime.js";
import { ApiEnvelope } from "../types.js";
import { requestIdOf, withoutTrailingSlash } from "./utils.js";
import { BackendError } from "./backend-error.js";

export class HttpClient {
    private refreshPromise: Promise<boolean> | null = null;

    constructor(
        private readonly baseUrl: string,
        private readonly store: SessionStore,
        private readonly opts: {
            autoRefresh: boolean;
            fetch: typeof fetch;
            headers?: Record<string, string>;
            /** Called once per HTTP round trip, including the retry after a refresh. */
            onRequest?: RequestObserver;
        },
        /** Performs the refresh; returns true on success. Injected to avoid a cycle. */
        private readonly doRefresh: () => Promise<boolean>,
    ) { }

    /**
     * Install (or clear) the request observer.
     *
     * Set rather than constructed, so `client.on('request', ...)` can be called
     * after the client exists, and cleared again when the last listener goes: the
     * timing path is skipped entirely while nobody is watching.
     */
    setRequestObserver(observer: RequestObserver | undefined): void {
        this.opts.onRequest = observer;
    }

    async request<T>(path: string, options: RequestOptions = {}): Promise<T> {
        return (await this.requestWithHeaders<T>(path, options)).data;
    }

    /**
     * Like `request`, but keeps the response headers. PostgREST puts the row count
     * in `Content-Range`, which is unreachable from the parsed body alone.
     */
    async requestWithHeaders<T>(
        path: string,
        options: RequestOptions = {},
    ): Promise<{ data: T; headers: Headers; status: number }> {
        const res = await this.sendWithRefresh(path, options);
        const data = options.raw ? await this.parseRaw<T>(res) : await this.parse<T>(res);
        return { data, headers: res.headers, status: res.status };
    }

    /** Like `request`, but returns the raw Response (for binary downloads). */
    async requestRaw(path: string, options: RequestOptions = {}): Promise<Response> {
        const res = await this.sendWithRefresh(path, options);
        if (!res.ok) {
            await this.parseRaw(res);
        }
        return res;
    }

    private async sendWithRefresh(path: string, options: RequestOptions): Promise<Response> {
        const res = await this.send(path, options);
        if (res.status === 401 && this.opts.autoRefresh && !options.anonymous && !options._retry) {
            const refreshed = await this.refreshOnce();
            if (refreshed) {
                return this.send(path, { ...options, _retry: true });
            }
        }
        return res;
    }

    /** Shared single-flight refresh: concurrent callers await the same promise. */
    private refreshOnce(): Promise<boolean> {
        if (!this.refreshPromise) {
            this.refreshPromise = this.doRefresh().finally(() => {
                this.refreshPromise = null;
            });
        }
        return this.refreshPromise;
    }

    private async send(path: string, options: RequestOptions): Promise<Response> {
        await this.store.hydrate();
        const headers: Record<string, string> = { ...this.opts.headers, ...options.headers };
        const session = this.store.get();
        if (!options.anonymous && session?.accessToken) {
            headers['Authorization'] = `Bearer ${session.accessToken}`;
        }

        let body: BodyInit | undefined;
        if (options.form) {
            // A JSON default must not replace the multipart boundary generated by fetch.
            for (const name of Object.keys(headers)) {
                if (name.toLowerCase() === 'content-type') delete headers[name];
            }
            body = options.form; // browser/runtime sets the multipart boundary
        } else if (options.body !== undefined) {
            headers['Content-Type'] = 'application/json';
            body = JSON.stringify(options.body);
        }

        const method = options.method ?? 'GET';
        if (!isBrowser() && !['GET', 'HEAD', 'OPTIONS'].includes(method.toUpperCase())
            && path.startsWith(`${HTTP_ROUTES.auth}/`)
            && !Object.keys(headers).some(name => name.toLowerCase() === 'origin')) {
            // Node does not supply Origin. Better Auth may require it for mutations,
            // including requests carrying cookies. Keep its CSRF checks enabled.
            headers.Origin = new URL(this.baseUrl).origin;
        }
        return this.observe(method, path, () => this.opts.fetch(this.url(path), {
            method,
            headers,
            body,
            signal: options.signal,
            ...(options.credentials ? { credentials: options.credentials } : {}),
        }));
    }

    /**
     * `fetchImpl`, reporting each round trip to the request observer. The auth
     * client sends through Better Auth's own fetch, which is handed this. It
     * passes a `URL`; the app's fetch gets a string, as from every other call.
     */
    observedFetch(fetchImpl: typeof fetch): typeof fetch {
        return (input, init) => {
            const href = input instanceof Request ? input.url : String(input);
            const url = new URL(href);
            return this.observe(init?.method ?? 'GET', `${url.pathname}${url.search}`, () =>
                fetchImpl(input instanceof Request ? input : href, init));
        };
    }

    private async observe(method: string, path: string, send: () => Promise<Response>): Promise<Response> {
        // Timed only when someone is listening: reading the clock twice per request
        // for an observer nobody registered is a cost every app pays for a feature
        // most do not use.
        if (!this.opts.onRequest) return send();
        const startedAt = Date.now();
        try {
            const res = await send();
            this.emit({ method, path, status: res.status, durationMs: Date.now() - startedAt, requestId: requestIdOf(res) });
            return res;
        } catch (error) {
            this.emit({ method, path, status: 0, durationMs: Date.now() - startedAt, error });
            throw error;
        }
    }

    /** An observer that throws must not fail the request it was watching. */
    private emit(event: RequestEvent): void {
        try {
            this.opts.onRequest?.(event);
        } catch {
            // an observer is a spectator
        }
    }

    private async parse<T>(res: Response): Promise<T> {
        let envelope: ApiEnvelope<T> | undefined;
        try {
            envelope = (await res.json()) as ApiEnvelope<T>;
        } catch {
            // non-JSON response
        }

        if (!res.ok || (envelope && envelope.status === 0)) {
            const message = envelope?.message ?? `Request failed with status ${res.status}`;
            throw new BackendError(message, res.status, envelope?.status, envelope?.code, requestIdOf(res) ?? envelope?.requestId);
        }

        // `in`, not `??`: a legitimate `data: null` must come back as null, not as the envelope.
        return (envelope && typeof envelope === 'object' && 'data' in envelope ? envelope.data : envelope) as T;
    }

    /** Parse a plain-JSON (non-envelope) response, mapping failures to BackendError. */
    private async parseRaw<T>(res: Response): Promise<T> {
        let body: unknown;
        try {
            body = await res.json();
        } catch {
            body = undefined;
        }
        if (!res.ok) {
            const failure = (body ?? {}) as { message?: string; code?: string; requestId?: string };
            const message = failure.message ?? `Request failed with status ${res.status}`;
            throw new BackendError(message, res.status, undefined, failure.code, requestIdOf(res) ?? failure.requestId);
        }
        return body as T;
    }

    /** Absolute URL for a path. Public so callers can navigate to an endpoint
     *  rather than fetch it (see the `signIn.social` redirect in auth.ts). */
    url(path: string): string {
        return `${withoutTrailingSlash(this.baseUrl)}${path}`;
    }
}