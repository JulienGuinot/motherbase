/**
 * Pick the session storage from either options shape.
 *
 * Precedence: the native `storage` (explicit and already the right shape), then
 * supabase-js's `auth.storage` (wrapped if it is a key/value store), then
 * `auth.persistSession` on its own, which in supabase-js means localStorage.
 * Returns `undefined` when nothing was asked for, so the caller can tell "no
 * choice made" from "memory was chosen" and warn accordingly.
 */
function resolveStorage(options: ClientOptions): SessionStorageAdapter | undefined {
  if (options.storage) return options.storage;

  const key = options.auth?.storageKey;
  const provided = options.auth?.storage;
  if (provided) {
    return isKeyValueStorage(provided) ? keyValueStorage(provided, key) : provided;
  }
  if (options.auth?.persistSession === true) return localStorageStorage(key);
  if (options.auth?.persistSession === false) return memoryStorage();
  return undefined;
}

/**
 * Supabase-js-compatible client for a Motherbase backend.
 *
 * Drop-in shaped: `client.from(table).select()…`, `client.auth.signIn.email()` (Better Auth),
 * `client.storage.from(bucket)`, `client.channel(name)`, `client.functions.invoke()`.
 *
 * Pass the type generated by `motherbase gen types typescript` to get real
 * inference: `createClient<Database>(url, key)` then types every row, rejects
 * unknown columns in `.select()`, checks `.insert()` payloads against the
 * Insert shape and types `.rpc()` from `Functions`. Without it the client
 * behaves exactly as it did before generics existed.
 */
export class MotherbaseClient<
  Database = GenericDatabase,
  SchemaName = DefaultSchemaName<Database>,
  Schema extends GenericSchema = SchemaOf<Database, SchemaName>,
> {
  /** Sign-up, sign-in, sessions and users: Better Auth's client, plus the supabase-js session methods. */
  readonly auth: AuthClient;
  /** File storage: `client.storage.from(bucket).upload(path, file)`. */
  readonly storage: StorageClient<Database>;
  /** Edge functions: `client.functions.invoke(name, { body })`. */
  readonly functions: FunctionsClient<Database>;
  /** Low-level realtime transport. Prefer `channel()` for the Supabase surface. */
  readonly realtime: RealtimeModule;
  /**
   * Prisma-style access to the same tables as `from()`, for those who prefer it:
   * `client.db.posts.findMany({ where: { published: true }, take: 20 })`.
   * Typed from the generated `Database`; throws on failure instead of resolving
   * `{ data, error }`. See `database/facade.ts`.
   */
  readonly db: DatabaseFacade<Schema> = new Proxy({} as DatabaseFacade<Schema>, {
    // A symbol is not a table name: a debugger or `await client.db` probing one gets nothing.
    get: (_, table) => (typeof table === 'string'
      ? tableFacade(() => new PostgrestQueryBuilder(this.http, table, this.compat))
      : undefined),
  });

  private readonly http: HttpClient;
  private readonly store: SessionStore;
  private readonly channels = new Map<string, RealtimeChannel>();
  private static warnedAboutStorage = false;
  /** `options.compat === 'supabase'`, read by every query builder this client makes. */
  private readonly compat: boolean;
  private readonly requestObservers = new Set<RequestObserver>();

  constructor(
    url: string,
    readonly key?: string,
    options: ClientOptions = {},
  ) {
    // `globalThis.fetch` is a native function that requires `this === window`
    // (or an equivalent global) when invoked: copying the reference without
    // binding it throws "Illegal invocation" the moment it's called as
    // `this.opts.fetch(...)` inside HttpClient. Bind it once here.
    const fetchImpl = options.fetch ?? options.global?.fetch ?? globalThis.fetch?.bind(globalThis);
    if (!fetchImpl) {
      throw new Error('No fetch implementation found. Pass `fetch` in options for this runtime.');
    }
    const autoRefresh = options.autoRefresh ?? options.auth?.autoRefreshToken ?? true;
    const headers: Record<string, string> = { ...options.global?.headers, ...options.headers };
    if (key) headers['apikey'] = key;
    this.compat = options.compat === 'supabase';

    // Tables are served from `public` only. A ported app that made another
    // schema its default would otherwise read `public` under a different name
    // and find the wrong rows (or none), which is far harder to diagnose than
    // the error it gets here. Functions in an exposed schema stay reachable
    // through `client.schema(name).rpc()`.
    const schema = options.db?.schema;
    if (schema && schema !== 'public') {
      throw new Error(
        `db.schema: '${schema}' is not exposed as the default schema. The Motherbase REST API serves tables from `
        + `public only. Call functions in another schema with client.schema('${schema}').rpc().`,
      );
    }

    // A secret key runs every request as service_role, which bypasses row level
    // security. In a browser it is readable by anyone who opens devtools, so it
    // is not "a key that leaked", it is the whole database published. Warn
    // rather than throw: a legitimate caller may run in a runtime that defines
    // `window` (a test harness, an Electron main process), and refusing to
    // construct would break them for a heuristic. `window`, not `isBrowser()`:
    // a React Native bundle ships the key to every device just the same.
    if (key?.startsWith('mb_secret_') && typeof window !== 'undefined') {
      console.warn(
        '[motherbase] A secret API key was passed to createClient in a browser context. '
        + 'Secret keys bypass row level security and must stay server side. '
        + 'Use the publishable key here.',
      );
    }

    const storageAdapter = resolveStorage(options);

    // The default adapter keeps the session in memory only: it does not survive
    // a reload, and the server never sees it. That is the right default for a
    // script or a test, and a bug in a browser app, and it presents as
    // "getSession() returns null everywhere", which reads like an auth problem
    // rather than a storage one. Point at the fix once, in development.
    if (!storageAdapter && isBrowser() && !MotherbaseClient.warnedAboutStorage) {
      MotherbaseClient.warnedAboutStorage = true;
      if (!isProduction()) {
        console.warn(
          '[motherbase] createClient() was called in a browser without a `storage` adapter, so the '
          + 'session lives in memory and is lost on reload. Pass `storage: cookieStorage()` (or '
          + '`localStorageStorage()`), or use `createBrowserClient` from `@motherbase/ssr`, which '
          + 'writes the cookie the server needs to read.',
        );
      }
    }

    this.store = new SessionStore(storageAdapter ?? memoryStorage());

    // auth needs the http client, and http revalidates through auth on a 401,
    // so wire them in two steps with a late-bound callback. A session the
    // server no longer knows answers get-session with null, and the session
    // sync in auth.ts clears it.
    // prefer-const cannot see the closure above: `auth` is read by the refresh
    // callback before this line's assignment happens, so it has to be a `let`.
    // eslint-disable-next-line prefer-const
    let auth!: AuthClient;
    this.http = new HttpClient(url, this.store, {
      autoRefresh,
      fetch: fetchImpl,
      headers,
      accessTokens: options.accessTokens ?? true,
    }, async () => {
      try {
        return Boolean((await auth.getSession()).data);
      } catch {
        return false; // unreachable server: keep the session, fail the request
      }
    });
    const flowType = options.auth?.flowType ?? 'implicit';
    const keyValue = options.auth?.storage && isKeyValueStorage(options.auth.storage) ? options.auth.storage : undefined;
    auth = createAuthClient(this.http, this.store, {
      url,
      fetch: fetchImpl,
      headers,
      flowType,
      verifiers: verifierStore(options.auth?.storageKey ?? SESSION_COOKIE_KEY, keyValue),
    });
    this.auth = auth;
    this.storage = new StorageClient<Database>(this.http, url, fetchImpl);
    this.functions = new FunctionsClient<Database>(this.http);
    this.realtime = new RealtimeModule(url, this.store, fetchImpl, options.realtimeIoFactory);

    // supabase-js finishes an OAuth redirect on its own (detectSessionInUrl
    // defaults to true), so ported code never calls anything after the provider
    // sends the browser back. Do the same, and only when there is actually a
    // token in the fragment: on every other page load this is a no-op with no
    // network call. Opt out with `auth: { detectSessionInUrl: false }`.
    if (
      options.auth?.detectSessionInUrl !== false
      && isBrowser()
      && window.location?.hash?.includes('access_token=')
    ) {
      void this.auth.getSessionFromUrl();
    }
    // The PKCE equivalent: a `?code=` on the page the provider sent us back to.
    // Stripped from the address bar first, so a reload cannot replay it.
    if (options.auth?.detectSessionInUrl !== false && flowType === 'pkce' && isBrowser()) {
      const url = new URL(window.location.href);
      const code = url.searchParams.get('code');
      if (code) {
        url.searchParams.delete('code');
        window.history?.replaceState?.(window.history.state, '', url.href);
        void this.auth.exchangeCodeForSession(code);
      }
    }
  }

  /**
   * Start a PostgREST-style query against a table or view.
   *
   * The first overload is the typed path: with a generated `Database` the
   * relation name is checked and the row/insert/update types come from it.
   * The second keeps the pre-generics form (`from<MyRow>('t')`) working; its
   * `never` default makes the parameter unusable unless `Row` is passed
   * explicitly, so a bare `from('typo')` still has to satisfy the first
   * overload rather than silently falling through to an unchecked one.
   */
  from<Name extends RelationName<Schema>>(
    table: Name,
  ): TypedQuery<RowOf<Schema, Name>, InsertOf<Schema, Name>, UpdateOf<Schema, Name>>;
  from<Row extends object = never>(
    table: [Row] extends [never] ? never : string,
  ): TypedQuery<Row, Partial<Row>, Partial<Row>>;
  from(table: string): unknown {
    return new PostgrestQueryBuilder(this.http, table, this.compat);
  }

  /**
   * Call a database function, typed from the generated `Functions` map.
   *
   * The transport is `POST /rest/v1/rpc/<fn>`, which the REST layer gains in
   * Phase 2.8. The typing is independent of that work: it reads only the
   * generated `Database`, so it is correct the moment the route exists.
   *
   * `get` and `head` switch to the read-only forms, which carry their arguments
   * as query parameters rather than as a body, exactly as supabase-js does.
   */
  async rpc<Name extends FunctionName<Schema>>(
    fn: Name,
    args?: FunctionArgs<Schema, Name>,
    options: RpcOptions = {},
  ): Promise<PostgrestResponse<FunctionReturns<Schema, Name>>> {
    return callRpc<FunctionReturns<Schema, Name>>(this.http, 'public', fn, args, options);
  }

  /**
   * Watch every HTTP request this client makes.
   *
   * One event per round trip, with method, path, status, duration and the
   * `x-request-id` the server logged it under. That id is the whole point: it
   * is what turns "a query was slow for a user yesterday" into a line in the
   * project's logs.
   *
   * ```ts
   * client.on('request', e => console.log(e.method, e.path, e.status, e.durationMs))
   * ```
   *
   * Returns the unsubscribe function. An observer that throws is ignored: it is
   * a spectator, and a broken logger must not fail the request it was logging.
   */
  on(event: 'request', listener: RequestObserver): () => void {
    if (event !== 'request') throw new Error(`Unknown client event '${String(event)}'. Only 'request' exists.`);
    this.requestObservers.add(listener);
    this.syncRequestObserver();
    return () => {
      this.requestObservers.delete(listener);
      this.syncRequestObserver();
    };
  }

  private syncRequestObserver(): void {
    this.http.setRequestObserver(
      this.requestObservers.size
        ? (event: RequestEvent) => {
          for (const listener of this.requestObservers) listener(event);
        }
        : undefined,
    );
  }

  /**
   * Several writes, applied in one database transaction, all or nothing.
   *
   * supabase-js has no equivalent. What people write instead is a sequence of
   * awaited writes inside a `try`, which is not a rollback: whatever already
   * committed stays committed, and the catch block is left holding half a
   * change it cannot undo.
   *
   * The callback does not await anything. It DESCRIBES the writes; they are
   * sent together and applied together:
   *
   * ```ts
   * const { data, error } = await client.transaction(tx => {
   *   tx.from('orders').insert({ id, total })
   *   tx.from('stock').update({ count: 4 }).eq('sku', sku)
   * })
   * ```
   *
   * `data` is one result array per operation, in the order they were declared.
   * Reads are refused: a batch exists to make writes atomic, and a read in the
   * middle of one invites expectations about ordering that nothing guarantees.
   */
  async transaction(build: (tx: TransactionContext) => void): Promise<PostgrestResponse<unknown[][]>> {
    const recorded: PostgrestQueryBuilder<Record<string, unknown>>[] = [];
    let collecting = true;
    const tx: TransactionContext = {
      from: ((table: string) => {
        if (!collecting) throw new Error('transaction(): the callback has already finished.');
        const builder = new PostgrestQueryBuilder(this.http, table, this.compat, true);
        recorded.push(builder);
        return builder;
      }) as unknown as TransactionContext['from'],
    };

    try {
      // Async callbacks that await a builder reject locally, before any write.
      try {
        await build(tx);
      } finally {
        collecting = false;
      }
      const operations = recorded.map(builder => {
        const request = builder.toRequest();
        if (request.method === 'GET' || request.method === 'HEAD') {
          throw new Error(
            `transaction(): '${request.model}' was read, not written. A transaction takes writes only `
            + '(insert, update, delete).',
          );
        }
        return request;
      });
      if (!operations.length) {
        throw new Error('transaction(): the callback declared no writes.');
      }

      const result = await this.http.request<{ results: unknown[][] }>(`${contractPath.rest('batch')}`, {
        method: 'POST',
        body: { operations },
      });
      return { data: result.results, error: null, count: null };
    } catch (err) {
      return { data: null, error: toError(err), count: null };
    }
  }

  /** Create (or reuse) a realtime channel. */
  channel(name: string, opts: RealtimeChannelOptions = {}): RealtimeChannel {
    const existing = this.channels.get(name);
    if (existing) return existing;
    const channel = new RealtimeChannel(name, this.realtime, opts);
    this.channels.set(name, channel);
    return channel;
  }

  /** Every channel this client created, as supabase-js reports them. */
  getChannels(): RealtimeChannel[] {
    return Array.from(this.channels.values());
  }

  /**
   * supabase-js's schema switcher.
   *
   * `'public'` returns this client. Any other schema returns its functions (see
   * `SchemaClient`): the REST layer serves tables from `public` only, and calls
   * functions in the schemas a feature exposes, such as Queues' `pgmq_public`.
   */
  schema(name: 'public'): this;
  schema<Name extends string>(name: Name): SchemaClient<SchemaOf<Database, Name>>;
  schema(name: string): this | SchemaClient {
    if (name === 'public') return this;
    const scoped: SchemaClient = {
      rpc: (fn, args, options = {}) => callRpc(this.http, name, fn, args, options),
      from: table => {
        throw new Error(
          `schema('${name}').from('${table}') is not supported: the Motherbase REST API serves tables from the `
          + `public schema only. Functions in '${name}' can be called with schema('${name}').rpc().`,
        );
      },
    };
    return scoped;
  }

  /** Unsubscribe and drop a channel. */
  async removeChannel(channel: RealtimeChannel): Promise<'ok'> {
    await channel.unsubscribe();
    this.channels.delete(channel.topic);
    return 'ok';
  }

  /** Unsubscribe and drop every channel. */
  async removeAllChannels(): Promise<'ok'> {
    await Promise.all(Array.from(this.channels.values()).map(c => c.unsubscribe()));
    this.channels.clear();
    return 'ok';
  }

  /**
   * Load the persisted session and return it, without a network call. It is
   * whatever the storage held, unverified: authorize on `auth.getSession()`,
   * which asks the server.
   */
  hydrate(): Promise<Session | null> {
    return this.store.hydrate();
  }
}

/**
 * Create a Supabase-compatible Motherbase client.
 *
 * In a Next.js app, prefer `createBrowserClient` / `createServerClient` from
 * `@motherbase/ssr`: they persist the session to a cookie both halves can read.
 * `createClient()` on its own keeps the session in memory, which the server
 * cannot see, so every server-rendered `auth.getSession()` returns null.
 *
 * @param url  Backend API base URL.
 * @param key  Anon/publishable key (optional). Sent as an `apikey` header.
 * @param options  Session storage, fetch override, extra headers.
 *
 * @example
 * ```ts
 * import type { Database } from './database.types'
 * const client = createClient<Database>(url, anonKey)
 * ```
 */
export function createClient<
  Database = GenericDatabase,
  SchemaName = DefaultSchemaName<Database>,
  Schema extends GenericSchema = SchemaOf<Database, SchemaName>,
>(url: string, key?: string, options: ClientOptions = {}): MotherbaseClient<Database, SchemaName, Schema> {
  return new MotherbaseClient<Database, SchemaName, Schema>(url, key, options);
}

