import crypto from 'crypto';

/** Cryptographically strong hex secret (default 48 bytes → 96 hex chars). */
export function generateSecret(bytes = 48): string {
  return crypto.randomBytes(bytes).toString('hex');
}

export interface SetupArgs {
  yes: boolean;
  help: boolean;
}

/**
 * Extract the host and port a Postgres connection string points at, so the
 * wizard can probe the *actual* database (custom port, remote host) instead of
 * assuming localhost:5432. Falls back to localhost:5432 when the URL can't be
 * parsed.
 */
export function parseDbHostPort(databaseUrl: string): { host: string; port: number } {
  try {
    const u = new URL(databaseUrl);
    return {
      host: u.hostname || 'localhost',
      port: u.port ? Number(u.port) : 5432,
    };
  } catch {
    return { host: 'localhost', port: 5432 };
  }
}

/** Parse the handful of flags the setup wizard understands. */
export function parseArgs(argv: string[]): SetupArgs {
  const has = (...flags: string[]) => flags.some(f => argv.includes(f));
  return {
    yes: has('--yes', '-y'),
    help: has('--help', '-h'),
  };
}

export interface SetupAnswers {
  port: number;
  databaseUrl: string;
  jwtSecret: string;
  configEncryptionKey: string;
  edgeRuntimeToken: string;
  accessTokenExpMin: number;
  refreshTokenExpDays: number;
  corsOrigins: string;
  storageDriver: 'local' | 's3';
  s3Endpoint: string;
  s3Region: string;
  s3AccessKeyId: string;
  s3SecretAccessKey: string;
  s3Bucket: string;
  s3PublicUrl: string;
  consoleSqlEnabled: boolean;
  seedAdminEmail: string;
  seedAdminPassword: string;
}

/**
 * Sensible defaults for a local dev setup, matching the docker-compose stack.
 * Carries a freshly generated JWT secret so a fresh checkout is never insecure.
 */
export function defaultAnswers(): SetupAnswers {
  return {
    port: 5001,
    databaseUrl: 'postgresql://postgres:postgres@localhost:5432/app?schema=public',
    jwtSecret: generateSecret(),
    configEncryptionKey: crypto.randomBytes(32).toString('base64'),
    edgeRuntimeToken: generateSecret(),
    accessTokenExpMin: 15,
    refreshTokenExpDays: 30,
    corsOrigins: '',
    storageDriver: 'local',
    s3Endpoint: 'http://localhost:9000',
    s3Region: 'us-east-1',
    s3AccessKeyId: 'minioadmin',
    s3SecretAccessKey: 'minioadmin',
    s3Bucket: 'uploads',
    s3PublicUrl: 'http://localhost:9000/uploads',
    consoleSqlEnabled: true,
    seedAdminEmail: 'admin@example.com',
    seedAdminPassword: generateSecret(24),
  };
}

/** Render a complete, ready-to-run `.env` from the collected answers. */
export function buildEnvFile(a: SetupAnswers): string {
  const lines = [
    '# Generated by `./setup.sh`. Edit freely; re-run setup to regenerate.',
    '',
    '# --- Server ---',
    `PORT=${a.port}`,
    `BASE_HOST=localhost:${a.port}`,
    '',
    '# --- Database (PostgreSQL) ---',
    `DATABASE_URL=${a.databaseUrl}`,
    '',
    '# --- Auth ---',
    `JWT_SECRET=${a.jwtSecret}`,
    `ACCESS_TOKEN_EXP_MIN=${a.accessTokenExpMin}`,
    `REFRESH_TOKEN_EXP_DAYS=${a.refreshTokenExpDays}`,
    '',
    '# --- Config secret encryption (console-managed secrets at rest) ---',
    `CONFIG_ENCRYPTION_KEY=${a.configEncryptionKey}`,
    '',
    '# --- Edge runtime (Deno sidecar; `npm run edge-runtime` locally) ---',
    `EDGE_RUNTIME_TOKEN=${a.edgeRuntimeToken}`,
    `EDGE_RUNTIME_URL=http://localhost:9000`,
    `EDGE_RUNTIME_CALLBACK_URL=http://localhost:${a.port}`,
    '',
    '# --- CORS (comma-separated; empty = allow all, dev only) ---',
    `CORS_ORIGINS=${a.corsOrigins}`,
    '',
    '# --- Storage ---',
    `STORAGE_DRIVER=${a.storageDriver}`,
    `S3_ENDPOINT=${a.s3Endpoint}`,
    `S3_REGION=${a.s3Region}`,
    `S3_ACCESS_KEY_ID=${a.s3AccessKeyId}`,
    `S3_SECRET_ACCESS_KEY=${a.s3SecretAccessKey}`,
    `S3_BUCKET=${a.s3Bucket}`,
    `S3_PUBLIC_URL=${a.s3PublicUrl}`,
    '',
    '# --- Console dashboard ---',
    `CONSOLE_SQL_ENABLED=${a.consoleSqlEnabled}`,
    'CONSOLE_LOG_BUFFER_SIZE=500',
    '',
    '# --- Seed ---',
    `SEED_ADMIN_EMAIL=${a.seedAdminEmail}`,
    `SEED_ADMIN_PASSWORD=${a.seedAdminPassword}`,
    '',
  ];
  return lines.join('\n');
}
