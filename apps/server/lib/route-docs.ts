/**
 * Editorial notes rendered between a section's heading and its table.
 *
 * The generator overwrites `docs/admin-routes.md` whole, so a paragraph typed
 * into that file survives exactly until the next `npm run docs:routes` and the
 * freshness test goes red in the meantime. Prose that belongs to a section
 * lives here instead, which is the same place its title already lives.
 */
const SECTION_NOTES: Record<string, string> = {
  'admin/admin-observability.controller.ts':
    '`GET /api/admin/logs` accepts `limit` (default 500, capped at 5000), `since`\n' +
    '(ISO timestamp or epoch ms), `level`, `source` (repeated or comma-separated) and\n' +
    '`q`. It answers from `platform.request_logs` when log storage is on\n' +
    '(`logs.retention`), and from the in-memory ring buffer otherwise; the response\n' +
    'carries `persisted`, `retentionDays` and `oldestAvailable` alongside `logs`.',
};

/** Order sections by title so the page reads the same way every time. */
function sectionsOf(manifest: RouteEntry[]): Array<{ source: string; title: string; routes: RouteEntry[] }> {
  const bySource = new Map<string, RouteEntry[]>();
  for (const route of manifest) {
    // Relative to controllers/, so a subfolder survives into the Source line.
    const file = route.source.replace(/^apps\/server\/controllers\//, '');
    const list = bySource.get(file) ?? [];
    list.push(route);
    bySource.set(file, list);
  }
  return [...bySource.entries()]
    .map(([source, routes]) => ({ source, title: SECTION_TITLES[source] ?? source, routes }))
    .sort((a, b) => a.title.localeCompare(b.title));
}

/** Escape the pipe so a guard containing one cannot break the table. */
const cell = (value: string) => value.replace(/\|/g, '\\|');

export function renderRouteDocs(manifest: RouteEntry[] = readRouteManifest()): string {
  const lines: string[] = [
    '<!-- GENERATED by `npm run docs:routes` from the controller decorators. Do not edit by hand. -->',
    '',
  ];

  for (const section of sectionsOf(manifest)) {
    lines.push(`## ${section.title}`, '');
    lines.push(`Source: \`apps/server/controllers/${section.source}\``, '');
    const note = SECTION_NOTES[section.source];
    if (note) lines.push(note, '');
    lines.push('| Method | Path | Handler | Guards |');
    lines.push('|---|---|---|---|');
    for (const route of section.routes) {
      const guards = route.guards.length
        ? route.guards.map(guard => `\`${cell(guard)}\``).join(', ')
        : '—';
      lines.push(`| \`${route.method}\` | \`${cell(route.path)}\` | \`${cell(route.handler)}\` | ${guards} |`);
    }
    lines.push('');
  }

  return lines.join('\n');
}
