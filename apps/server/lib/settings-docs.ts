import { SETTINGS_GROUPS, type FieldDef, type GroupDef } from '../config/settings';

/**
 * Render the settings registry as the Markdown published in the docs.
 *
 * The reference page claimed to be "generated from the settings registry" while
 * being typed by hand, and it had drifted: five groups
 * (`auth.attackProtection`, `auth.rateLimits`, `auth.thirdParty`,
 * `storage.imageTransform`, `storage.s3`) existed in the registry and nowhere on
 * the page, and the "groups at a glance" table counted 36 of 42.
 *
 * Everything on the page except the notes below comes from the one object the
 * console UI, the settings service and the project-defaults service already
 * share, so the three cannot disagree about what an operator can set.
 */

/**
 * Editorial paragraphs rendered after a group's table.
 *
 * The generator overwrites `docs/settings.md` whole, so a paragraph typed into
 * that file survives exactly until the next `npm run docs:settings`. Prose that
 * belongs to a group lives here instead — the same arrangement the route table
 * uses for its section notes.
 */
const GROUP_NOTES: Record<string, string> = {
  'security.rateLimit':
    'All six apply live. The window used to be the exception — `express-rate-limit` reads\n' +
    '`windowMs` once at construction — so the limiters are rebuilt when it changes. Saving the\n' +
    'group **without** changing the window does not rebuild, so a no-op save cannot hand every\n' +
    'throttled caller a fresh allowance.',
  'storage.policies':
    'Off by default because turning it on changes who can read every object in the project, and\n' +
    'an upgrade does not get to do that silently. The migration installs policies reproducing the\n' +
    'built-in behaviour, so switching over changes nothing until you write your own.',
  'api.rest':
    'Function names are stored verbatim: they are matched against `pg_proc.proname`, and a quoted\n' +
    '`CREATE FUNCTION "MyFn"` really is stored as `MyFn`, so case is not folded. Entries longer\n' +
    "than Postgres' 63-byte identifier limit, or carrying control characters, are rejected on save.",
  'api.keys':
    'Off by default so an app running against an older version keeps working across an upgrade.\n' +
    'Turn it on once your clients send the key: revoking a key then cuts that caller off without\n' +
    'touching a single policy. The keys themselves are not settings — they live in their own table\n' +
    'and are managed from Project Settings → API keys or `motherbase keys`.',
};

/** Escape the pipe so a help string containing one cannot break the table. */
const cell = (value: unknown) => String(value ?? '').replace(/\|/g, '\\|');

/** `undefined` is "no default"; an empty string is a default of empty. */
function defaultCell(field: FieldDef): string {
  if (field.default === undefined) return '—';
  if (field.default === '') return '`""`';
  if (typeof field.default === 'object') return `\`${cell(JSON.stringify(field.default))}\``;
  return `\`${cell(field.default)}\``;
}

/**
 * The field's note: its help text, then the choices a `select` offers, then
 * whether saving the group requires it. A field with none of the three is `—`,
 * rather than an empty cell that reads as a rendering bug.
 */
function notesCell(field: FieldDef): string {
  const parts: string[] = [];
  if (field.help) parts.push(cell(field.help));
  if (field.options?.length) {
    parts.push(`One of ${field.options.map(option => `\`${cell(option.value)}\``).join(', ')}.`);
  }
  if (field.required) parts.push('Required.');
  return parts.length ? parts.join(' ') : '—';
}

function renderGroup(group: GroupDef): string[] {
  const lines = [`### ${group.label}`, '', `Group key: \`${group.key}\``, ''];
  if (group.description) lines.push(group.description, '');

  lines.push('| Field | Type | Default | Secret | Notes |');
  lines.push('|---|---|---|---|---|');
  for (const field of group.fields) {
    const secret = field.secret || field.secretKeys?.length ? 'yes' : '—';
    lines.push(
      `| \`${cell(field.key)}\` — ${cell(field.label)} | \`${field.type}\` | ${defaultCell(field)} | ${secret} | ${notesCell(field)} |`,
    );
  }
  lines.push('');

  const note = GROUP_NOTES[group.key];
  if (note) lines.push(note, '');
  return lines;
}

export function renderSettingsDocs(groups: Record<string, GroupDef> = SETTINGS_GROUPS): string {
  const all = Object.values(groups);
  const lines: string[] = [
    '<!-- GENERATED by `npm run docs:settings` from apps/server/config/settings. Do not edit by hand. -->',
    '',
    '## Groups at a glance',
    '',
    '| Group key | Label | Fields | Holds a secret |',
    '|---|---|---|---|',
  ];

  for (const group of all) {
    const hasSecret = group.fields.some(field => field.secret || Boolean(field.secretKeys?.length));
    lines.push(`| \`${cell(group.key)}\` | ${cell(group.label)} | ${group.fields.length} | ${hasSecret ? 'yes' : '—'} |`);
  }
  lines.push('');

  // Registry order, which is the order the console lists them in: an operator
  // reading the page alongside the screen meets the groups in the same sequence.
  lines.push('## Every group', '');
  for (const group of all) lines.push(...renderGroup(group));

  return lines.join('\n');
}
