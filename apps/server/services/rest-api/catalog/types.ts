// The shapes of a catalog snapshot. Pure types: no imports, no runtime code, so
// any layer can describe a table without pulling the loader (and prisma) in.

/** Minimal executor shape: Prisma client, or a Prisma transaction client. */
export interface CatalogExecutor {
  $queryRawUnsafe<T = unknown>(query: string, ...values: unknown[]): Promise<T>;
}

export type CatalogRelKind = 'table' | 'partitioned' | 'view' | 'matview' | 'foreign';

/**
 * Postgres type-kind discriminator, straight from `pg_type.typtype`:
 * b=base, c=composite, d=domain, e=enum, p=pseudo, r=range, m=multirange.
 */
export type PgTypeKind = 'b' | 'c' | 'd' | 'e' | 'p' | 'r' | 'm';

export interface CatalogColumn {
  name: string;
  /** `pg_type.typname`, byte-identical to `information_schema.columns.udt_name`. */
  pgType: string;
  /** `format_type()` rendering, e.g. `character varying(255)`, `numeric(10,2)`. */
  formattedType: string;
  /** TypeScript type for codegen. See `pgTypeToTsType`. */
  tsType: string;
  nullable: boolean;
  /** True when INSERT may omit the column: an explicit DEFAULT or an identity. */
  hasDefault: boolean;
  /** The raw default expression, matching `information_schema.column_default`. */
  defaultExpr: string | null;
  isPk: boolean;
  /**
   * True when the database always produces the value and a write must not supply
   * one: STORED generated columns and `GENERATED ALWAYS AS IDENTITY`.
   * `GENERATED BY DEFAULT AS IDENTITY` is NOT generated (it is merely defaulted).
   */
  isGenerated: boolean;
  isArray: boolean;
  /** Qualified name of the user enum backing this column, when there is one. */
  enumType: string | null;
  typeKind: PgTypeKind;
  position: number;
}

type CatalogFkDirection = 'outbound' | 'inbound';

/**
 * A foreign key as seen FROM the table that holds this entry.
 *
 * `outbound`: this table's `fromCols` reference `toTable(toCols)`. Always to-one,
 * because an FK targets a unique key.
 *
 * `inbound`: `toTable` holds an FK pointing back at this table's `fromCols`.
 * `cardinality` is `one` only when the child's constraining columns are covered
 * by a unique index, which is exactly the rule PostgREST uses to decide whether
 * an embedded resource is an object or an array.
 */
export interface CatalogForeignKey {
  constraint: string;
  direction: CatalogFkDirection;
  fromCols: string[];
  toSchema: string;
  toTable: string;
  toCols: string[];
  cardinality: 'one' | 'many';
}

export interface CatalogTable {
  schema: string;
  name: string;
  kind: CatalogRelKind;
  columns: CatalogColumn[];
  primaryKey: string[];
  foreignKeys: CatalogForeignKey[];
  rlsEnabled: boolean;
  /** `relforcerowsecurity`: RLS also applies to the table owner. */
  rlsForced: boolean;
}

export interface CatalogEnum {
  schema: string;
  name: string;
  values: string[];
}

interface CatalogCompositeAttribute {
  name: string;
  pgType: string;
  formattedType: string;
  tsType: string;
  nullable: boolean;
}

export interface CatalogCompositeType {
  schema: string;
  name: string;
  attributes: CatalogCompositeAttribute[];
}

/** One argument of a callable function, in declaration order. */
export interface CatalogFunctionArg {
  name: string;
  position: number;
  /** `pg_proc.proargmodes`: i=in, o=out, b=inout, v=variadic, t=table. */
  mode: 'i' | 'o' | 'b' | 'v' | 't';
  pgType: string;
  formattedType: string;
  /** True when the declaration supplies a default, so a call may omit it. */
  hasDefault: boolean;
}

/**
 * A function callable through the `/rpc/` surface.
 *
 * `securityDefiner` is the field that matters most. A `SECURITY DEFINER`
 * function executes with the privileges of its OWNER, which on this deployment
 * is the table owner, and RLS does not apply to a table's owner unless the table
 * is `FORCE ROW LEVEL SECURITY`. Exposing one over REST would therefore hand any
 * anonymous caller a read/write path around every policy in the database, so the
 * REST layer refuses them unless an operator has explicitly allowlisted the name.
 */
export interface CatalogFunction {
  schema: string;
  name: string;
  args: CatalogFunctionArg[];
  /** `proretset`: the function returns `setof` / `returns table`. */
  returnsSet: boolean;
  returnPgType: string;
  returnTypeKind: PgTypeKind;
  /** Relation name when the return type is a table's composite row type. */
  returnRelation: string | null;
  /** `prosecdef`. See the note above: this is a security gate, not metadata. */
  securityDefiner: boolean;
  /** `provolatile`: i=immutable, s=stable, v=volatile. GET refuses `v`. */
  volatility: 'i' | 's' | 'v';
  /** True when the last argument is VARIADIC, which named calls cannot fill. */
  variadic: boolean;
}

export interface CatalogSnapshot {
  /** Monotonic token bumped by `invalidateCatalog()`; identifies this snapshot. */
  readonly version: number;
  readonly loadedAt: number;
  readonly tables: readonly CatalogTable[];
  readonly enums: readonly CatalogEnum[];
  readonly compositeTypes: readonly CatalogCompositeType[];
  readonly functions: readonly CatalogFunction[];
  /** Exact (case-sensitive) lookup, the way Postgres resolves a quoted name. */
  table(schema: string, name: string): CatalogTable | undefined;
  tablesIn(schema: string): CatalogTable[];
  enum(schema: string, name: string): CatalogEnum | undefined;
  /** Every overload of `name`, in the order Postgres reported them. */
  functionsNamed(schema: string, name: string): CatalogFunction[];
}
